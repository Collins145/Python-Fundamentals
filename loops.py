# Loops:

# Concept of repeating a process till a result is achieved

# 1) While loop

# Example
# Program that displays ALL the numbers from 20 to 25
#     Steps to Follow
# i) Initialize the first value and store it in the variable
# ii)Set a condition based on the range
# iii)Increment the values

number = 20

while number <= 25: #Condition
    print(number)
    number += 1


