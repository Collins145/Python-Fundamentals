# Data Type: Refers to the different types of data used in programming

# Types
# 1) Integers: Whole numbers (+or-)
age = 70 #Integer

# 2) Float: Decimal numbers
height = 3.14 #Float

# 3) String: Text characters
greeting = "Hello" #Strings
# N/B: Always put a string in double quotes

# 4) Boolean: True or False values ()
isPythonEasy = True #True boolean value
softwareEngineeringIsDifficult = False #False boolean value

# 5) Data Structures: Single variable stores many variables at the same time
        #  i) List:
cars = ["Mercedes", "Audi", "Range sport"] #List
      # N/B: Values in a list are ALWAYS ordered & changeable/mutable.

        # ii) Arrays: Data structure used to store multiple values under a single variable name

students = ["Collins", "Everline", "Bruno"]

print(students)

        # iii) Tupple:
fruits = ("apple", "banana", "cherry") #Tupple
        # N/B: Values in a tupple are ordered BUT unchangeable/immutable
        # Use normal brackets to represent elements in a tupple

    # iv) Set:
countries = {"Kenya", "USA", "China"} #Set
        # N/B: Values in a set are unordered and unchangeable/immutable

    # v) Dictionary: Stores data as key-value pairs (key = value)
    # Each key identifies an associated value
# N/B: Dictionaries are useful for representing structured information
student = {
    "name" : "Collins Omondi",
    "age" : 28,
    "course" : "Software Engineering",
    "registered" : True
}
print(age)
print(height)
print(greeting)
print(isPythonEasy)
print(student)
