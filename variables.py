# Variables: Container for storing values

firstname = "Collins"
lastname = "Omondi"
school = "eMobilis"
num1 = 100
num2 = 20
language = "Python"

print(firstname)
print(lastname)
print(school)

print(firstname, lastname, school, num1, num2, language)

print(num1+num2)


# N/B: Use commas to combine two or more variables & double quotes for other values not captured in variables
print(school, "is a coding school")
print(firstname, lastname, "is a Software developer")
